def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog=COMMAND,
        description=(
            "Apply to one explicit LinkedIn job or to the first eligible job from "
            "a persistent candidate queue, record a session and return JSON. "
            "Success is reported only when LinkedIn confirms the application."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=_HELP_EPILOG,
    )
    parser.add_argument(
        "--job",
        help="LinkedIn job id to apply to (mutually exclusive with --candidates)",
    )
    parser.add_argument(
        "--candidates",
        help=(
            "JSON array/object or TSV list of candidates; the first eligible job "
            "is applied and the queue is persisted in data/queue.json"
        ),
    )
    parser.add_argument(
        "--jd-dir",
        help=(
            "read JD text files as <job-id>.txt from this directory instead of "
            "LinkedIn's guest endpoint (offline runs and tests)"
        ),
    )
    parser.add_argument(
        "--requeue-reason",
        help=(
            "explicitly allow blocked ids in --candidates mode to return to the "
            "queue; the reason is recorded in the queue history"
        ),
    )
    parser.add_argument(
        "--target",
        type=int,
        default=DEFAULT_TARGET,
        help=(
            "stop after this many verified applications in --candidates mode "
            "(default: 1; use 20 for the daily run)"
        ),
    )
    parser.add_argument(
        "--max-seconds",
        type=float,
        help=(
            "time budget for the whole --candidates run in seconds; 0 disables "
            "it (default: 4h or $CAREER_OPS_RUN_MAX_SECONDS)"
        ),
    )
    parser.add_argument(
        "--max-attempts",
        type=int,
        help=(
            "attempts per job in one run (default: 2 or "
            "$CAREER_OPS_MAX_ATTEMPTS_PER_JOB)"
        ),
    )
    parser.add_argument(
        "--queue-low-watermark",
        type=int,
        help=(
            "run discovery only when the backlog is at or below this number "
            "(default: 5 or $CAREER_OPS_QUEUE_LOW_WATERMARK)"
        ),
    )
    parser.add_argument(
        "--cv",
        help=(
            "PDF to attach, bypassing the CV cache (default: $CAREER_OPS_CV; "
            "in --candidates mode without it the cache generates or reuses one)"
        ),
    )
    parser.add_argument(
        "--cv-min-score",
        type=float,
        help=(
            "override the CV reuse threshold (0-1; default: 0.90 from "
            "config/cv-cache.json or $CAREER_OPS_CV_MIN_SCORE)"
        ),
    )
    parser.add_argument(
        "--answers",
        help=(
            "answers JSON (default: $CAREER_OPS_ANSWERS, then the workspace or "
            "upstream config/answers-hermes.json)"
        ),
    )
    parser.add_argument(
        "--run-id",
        help="session directory name under output/sessions/ (default: UTC timestamp)",
    )
    parser.add_argument(
        "--adapter",
        choices=("real", "fake"),
        default="real",
        help="browser implementation; use fake for tests and demos (default: real)",
    )
    parser.add_argument(
        "--fake-scenario",
        choices=FAKE_SCENARIOS,
        default="success",
        help="outcome produced by --adapter fake (default: success)",
    )
    return parser


def main(
    argv: Sequence[str] | None = None,
    *,
    environ: Mapping[str, str] | None = None,
    clock: Callable[[], datetime] | None = None,
    monotonic: Callable[[], float] | None = None,
) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    if args.adapter != "fake" and args.fake_scenario != "success":
        parser.error("--fake-scenario requires --adapter fake")
    if args.job is not None and args.candidates is not None:
        parser.error("pass exactly one of --job or --candidates")
    if args.job is None and args.candidates is None:
        parser.error("pass one of --job or --candidates")
    if args.jd_dir and not args.candidates:
        parser.error("--jd-dir requires --candidates")
    if args.requeue_reason and not args.candidates:
        parser.error("--requeue-reason requires --candidates")
    if args.target < 1:
        parser.error("--target must be at least 1")
    if args.target != DEFAULT_TARGET and not args.candidates:
        parser.error("--target requires --candidates")
    if args.max_seconds is not None:
        if args.max_seconds < 0:
            parser.error("--max-seconds must be zero or greater")
        if not args.candidates:
            parser.error("--max-seconds requires --candidates")
    if args.max_attempts is not None:
        if args.max_attempts < 1:
            parser.error("--max-attempts must be at least 1")
        if not args.candidates:
            parser.error("--max-attempts requires --candidates")
    if args.queue_low_watermark is not None:
        if args.queue_low_watermark < 0:
            parser.error("--queue-low-watermark must be zero or greater")
        if not args.candidates:
            parser.error("--queue-low-watermark requires --candidates")
    if args.cv_min_score is not None:
        if not 0 < args.cv_min_score <= 1:
            parser.error("--cv-min-score must be between 0 and 1")
        if not args.candidates:
            parser.error("--cv-min-score requires --candidates")
    job_id = ""
    if args.job is not None:
        job_id = args.job.strip()
        if not job_id:
            parser.error("--job must not be empty")

    clock = clock or utcnow
    monotonic = monotonic or time.monotonic
    environment = load_environment(environ)
    try:
        paths = resolve_paths(environment)
        renderer_timeout = resolve_renderer_timeout(environment)
        apply_timeout = _positive_float(
            environment.get("CAREER_OPS_APPLY_TIMEOUT_SECONDS"),
            DEFAULT_APPLY_TIMEOUT_SECONDS,
            "CAREER_OPS_APPLY_TIMEOUT_SECONDS",
        )
        max_seconds = _run_max_seconds(args.max_seconds, environment)
        max_attempts = _run_max_attempts(args.max_attempts, environment)
        low_watermark = _run_low_watermark(args.queue_low_watermark, environment)
    except ValueError as exc:
        return _emit(
            _error_payload(
                job_id=job_id or None,
                reason="configuration_error",
                message=str(exc),
            ),
            EXIT_PRECONDITION,
        )

    cv, cv_error = _resolve_cv(
        args.cv,
        environment,
        paths,
        allow_cache=args.candidates is not None,
    )
    if cv_error is not None:
        return _emit(
            _error_payload(
                job_id=job_id or None,
                reason="cv_missing",
                message=cv_error,
            ),
            EXIT_PRECONDITION,
        )
    if cv is None and args.candidates is None:
        return _emit(
            _error_payload(
                job_id=job_id or None,
                reason="cv_missing",
                message="no CV to attach",
            ),
            EXIT_PRECONDITION,
        )

    answers: Path | None = None
    if args.adapter == "real":
        answers, answers_error = _resolve_answers(args.answers, environment, paths)
        if answers is None or answers_error is not None:
            return _emit(
                _error_payload(
                    job_id=job_id or None,
                    reason="answers_missing",
                    message=answers_error or "no answers file found",
                    cv=cv,
                ),
                EXIT_PRECONDITION,
            )

    if args.candidates is not None:
        return _run_queue(
            args,
            environment=environment,
            paths=paths,
            cv=cv,
            answers=answers,
            apply_timeout=apply_timeout,
            renderer_timeout=renderer_timeout,
            max_seconds=max_seconds,
            max_attempts=max_attempts,
            low_watermark=low_watermark,
            clock=clock,
            monotonic=monotonic,
        )

    assert cv is not None  # --job mode always resolves a CV or fails above
    adapter = _build_adapter(
        args.adapter,
        args.fake_scenario,
        paths,
        environment,
        job_id=job_id,
        cv=cv,
        answers=answers,
        apply_timeout=apply_timeout,
    )
    watchdog = _build_watchdog(args.adapter, renderer_timeout, apply_timeout)

    try:
        with RunLock(
            paths.data / LOCK_FILENAME,
            assert_writable=paths.assert_writable,
            clock=clock,
        ):
            session = SessionRecorder.create(
                paths,
                run_id=args.run_id,
                job={"id": job_id},
                screenshotter=adapter.capture,
                clock=clock,
            )

            payload = _run_application(
                session=session,
                adapter=adapter,
                watchdog=watchdog,
                job_id=job_id,
                cv=cv,
            )
    except RunLocked as exc:
        return _emit(
            _error_payload(job_id=job_id, reason="run_locked", message=str(exc), cv=cv),
            EXIT_PRECONDITION,
        )
    except ValueError as exc:
        reason = "invalid_run_id" if "run id" in str(exc) else "configuration_error"
        return _emit(
            _error_payload(job_id=job_id, reason=reason, message=str(exc), cv=cv),
            EXIT_USAGE if reason == "invalid_run_id" else EXIT_PRECONDITION,
        )
    return _emit(payload, _exit_code(payload))


def _run_queue(
    args: argparse.Namespace,
    *,
    environment: Mapping[str, str],
    paths: WorkspacePaths,
    cv: Path | None,
    answers: Path | None,
    apply_timeout: float,
    renderer_timeout: float,
    max_seconds: float | None,
    max_attempts: int,
    low_watermark: int,
    clock: Callable[[], datetime],
    monotonic: Callable[[], float],
) -> int:
    candidates_path = expand_path(args.candidates, environment)
    if not candidates_path.is_file():
        return _emit(
            _error_payload(
                job_id=None,
                reason="candidates_missing",
                message=f"candidate list not found: {candidates_path}",
                cv=cv,
            ),
            EXIT_PRECONDITION,
        )

    fetcher: JobDescriptionFetcher
    if args.jd_dir:
        jd_dir = expand_path(args.jd_dir, environment)
        if not jd_dir.is_dir():
            return _emit(
                _error_payload(
                    job_id=None,
                    reason="jd_source_missing",
                    message=f"JD directory not found: {jd_dir}",
                    cv=cv,
                ),
                EXIT_PRECONDITION,
            )
        fetcher = DirectoryJobDescriptionFetcher(jd_dir)
    else:
        fetcher = HttpJobDescriptionFetcher()

    try:
        rules = EligibilityRules.from_paths(paths)
    except ValueError as exc:
        return _emit(
            _error_payload(
                job_id=None,
                reason="configuration_error",
                message=str(exc),
                cv=cv,
            ),
            EXIT_PRECONDITION,
        )

    try:
        load_candidates(candidates_path)
    except ValueError as exc:
        return _emit(
            _error_payload(
                job_id=None,
                reason="invalid_candidates",
                message=str(exc),
                cv=cv,
            ),
            EXIT_USAGE,
        )

    run_id = args.run_id or clock().strftime("%Y%m%dT%H%M%SZ")
    try:
        validate_run_id(run_id)
        state = RunState.load_or_create(
            paths,
            run_id=run_id,
            target=args.target,
            clock=clock,
            assert_writable=paths.assert_writable,
        )
        queue = JobQueue.load(paths)
        config = LoopConfig(
            target=args.target,
            max_seconds=max_seconds,
            max_attempts_per_job=max_attempts,
            low_watermark=low_watermark,
        )
    except ValueError as exc:
        reason = "invalid_run_id" if "run id" in str(exc) else "configuration_error"
        return _emit(
            _error_payload(job_id=None, reason=reason, message=str(exc), cv=cv),
            EXIT_USAGE if reason == "invalid_run_id" else EXIT_PRECONDITION,
        )

    decisions: dict[str, CvDecision] = {}

    def resolve_cv(selection: Selection) -> tuple[Path, CvDecision | None]:
        if cv is not None:
            return cv, None
        decision = _select_cached_cv(
            args,
            environment=environment,
            paths=paths,
            selection=selection,
        )
        decisions[selection.job_id] = decision
        return decision.cv, decision

    def apply(selection: Selection, expected_cv: Path) -> Mapping[str, object]:
        adapter = _build_adapter(
            args.adapter,
            args.fake_scenario,
            paths,
            environment,
            job_id=selection.job_id,
            cv=expected_cv,
            answers=answers,
            apply_timeout=apply_timeout,
        )
        watchdog = _build_watchdog(args.adapter, renderer_timeout, apply_timeout)
        session = SessionRecorder.create(
            paths,
            run_id=run_id,
            job=selection.as_job(),
            screenshotter=adapter.capture,
            clock=clock,
            subdir=selection.job_id,
        )
        payload = _run_application(
            session=session,
            adapter=adapter,
            watchdog=watchdog,
            job_id=selection.job_id,
            cv=expected_cv,
            initial_job=selection.as_job(),
        )
        decision = decisions.get(selection.job_id)
        if decision is not None:
            payload["cv_cache"] = decision.as_dict()
        return payload

    try:
        with RunLock(
            paths.data / LOCK_FILENAME,
            assert_writable=paths.assert_writable,
            clock=clock,
        ):
            loop = DailyLoop(
                queue=queue,
                processor=QueueProcessor(queue, fetcher, rules=rules),
                source=FileCandidateSource(candidates_path),
                config=config,
                state=state,
                apply=apply,
                resolve_cv=resolve_cv,
                requeue_reason=args.requeue_reason,
                monotonic=monotonic,
            )
            outcome = loop.run()
    except RunLocked as exc:
        payload = _error_payload(job_id=None, reason="run_locked", message=str(exc), cv=cv)
        payload["target"] = args.target
        payload["stop_reason"] = "run_locked"
        return _emit(payload, EXIT_PRECONDITION)
    except ValueError as exc:
        return _emit(
            _error_payload(
                job_id=None,
                reason="configuration_error",
                message=str(exc),
                cv=cv,
            ),
            EXIT_PRECONDITION,
        )

    payload = _loop_payload(
        outcome,
        queue=queue,
        cv=cv,
    )
    return _emit(payload, _loop_exit_code(outcome))


def _loop_payload(
    outcome: LoopOutcome,
    *,
    queue: JobQueue,
    cv: Path | None,
) -> dict[str, object]:
    if outcome.last_payload is not None:
        payload = dict(outcome.last_payload)
    else:
        reason = (
            "no_eligible_job"
            if outcome.stop_reason == "queue_exhausted"
            else outcome.stop_reason
        )
        payload = _envelope(
            run_id=outcome.run_id,
            job={"id": None},
            cv=cv,
            result=SubmissionResult(submitted=False, attempts=0, reason=reason),
            message=_stop_message(outcome.stop_reason),
            artifacts=_empty_artifacts(),
        )

    selection = outcome.last_selection
    payload["queue"] = {
        "path": str(queue.path),
        "selection": selection.as_dict() if selection is not None else None,
        "ingested": [result.as_dict() for result in outcome.ingested],
        "record": (
            queue.get(selection.job_id).as_dict() if selection is not None else None
        ),
        "records": [record.as_dict() for record in queue.records.values()],
    }
    payload["target"] = outcome.target
    payload["submitted"] = outcome.verified
    payload["verified"] = outcome.verified
    payload["waiting"] = outcome.waiting
    payload["attempts"] = outcome.attempts
    payload["stop_reason"] = outcome.stop_reason
    payload["run"] = outcome.as_dict()
    payload["applications"] = [
        application.as_dict() for application in outcome.applications
    ]

    if outcome.stop_reason == "target_reached":
        payload["status"] = "verified"
        payload["failure"] = None
    else:
        payload["status"] = "failed"
        last_failure = payload.get("failure")
        last_verified = (
            outcome.last_payload is not None
            and outcome.last_payload.get("status") == "verified"
        )
        if last_verified and outcome.stop_reason != "daily_limit_reached":
            payload["failure"] = {
                "reason": outcome.stop_reason,
                "message": _stop_message(outcome.stop_reason),
                "retryable": True,
            }
        elif last_verified:
            payload["failure"] = {
                "reason": "daily_limit",
                "message": _stop_message(outcome.stop_reason),
                "retryable": False,
            }
        elif not isinstance(last_failure, Mapping):
            payload["failure"] = {
                "reason": outcome.stop_reason,
                "message": _stop_message(outcome.stop_reason),
                "retryable": False,
            }
    return payload


def _stop_message(stop_reason: str) -> str:
    return {
        "target_reached": "the verified target was reached",
        "queue_exhausted": (
            "no candidate passed the title/location filters and the eligibility rules"
        ),
        "time_budget_exhausted": "the run time budget was exhausted",
        "daily_limit_reached": "LinkedIn reported its daily application limit",
        "run_locked": "another run is already using this workspace",
    }.get(stop_reason, stop_reason.replace("_", " "))


def _loop_exit_code(outcome: LoopOutcome) -> int:
    if outcome.stop_reason == "target_reached":
        return EXIT_VERIFIED
    if outcome.stop_reason == "queue_exhausted" and outcome.waiting > 0:
        return EXIT_WAITING_INPUT
    return EXIT_FAILED


def _select_cached_cv(
    args: argparse.Namespace,
    *,
    environment: Mapping[str, str],
    paths: WorkspacePaths,
    selection: "Selection",
) -> CvDecision:
    if selection.profile is None:
        raise ValueError(f"job {selection.job_id} has no structured profile to cache from")
    profile = JobProfile.from_dict(selection.profile)
    if selection.jd_path is None:
        raise CvGenerationError(
            f"job {selection.job_id} has no stored JD for tailoring",
            reason="jd_missing",
        )
    try:
        jd_text = Path(selection.jd_path).read_text(encoding="utf-8", errors="replace")
    except OSError as exc:
        raise CvGenerationError(
            f"could not read the stored JD for job {selection.job_id}: {exc}",
            reason="jd_missing",
        ) from exc

    rules = CvCacheRules.from_paths(paths, environment).raised_to(args.cv_min_score)
    cache = CvCache.load(paths)
    tailor = _build_tailor(args.adapter, paths, environment)
    return CvSelector(cache, tailor, rules).resolve(
        profile,
        job=selection.as_job(),
        jd_text=jd_text,
    )


def _run_application(
    *,
    session: SessionRecorder,
    adapter: ApplicationAdapter,
    watchdog: RendererWatchdog,
    job_id: str,
    cv: Path,
    initial_job: Mapping[str, object] | None = None,
) -> dict[str, object]:
    session_status = "failed"
    job_payload: dict[str, object] = (
        dict(initial_job) if initial_job is not None else {"id": job_id}
    )
    try:
        info = adapter.open()
        job_payload = {**job_payload, **info.as_dict()}
        _capture(session, "open", job_id)
        blocker = info.blocker
        if blocker is not None:
            message = _BLOCKER_MESSAGES[blocker]
            session.fail(message, job_id=job_id, detail={"reason": blocker})
            return _payload(
                session=session,
                job=job_payload,
                cv=cv,
                result=SubmissionResult(submitted=False, attempts=0, reason=blocker),
                message=message,
            )

        guard = SubmissionGuard(session, watchdog, recover=adapter.recover)
        result = guard.submit(job_id=job_id, expected_cv=cv, adapter=adapter)
        if result.submitted:
            session_status = "completed"
        return _payload(
            session=session,
            job=job_payload,
            cv=cv,
            result=result,
            message=(
                "LinkedIn confirmed the application"
                if result.submitted
                else _reason_message(result.reason)
            ),
        )
    except WaitingForInput as exc:
        session.fail(
            exc,
            job_id=job_id,
            detail={"reason": exc.reason, "questions": list(exc.questions)},
        )
        return _payload(
            session=session,
            job=job_payload,
            cv=cv,
            result=SubmissionResult(
                submitted=False,
                attempts=0,
                reason=exc.reason,
                retryable=True,
            ),
            message=str(exc),
            questions=exc.questions,
        )
    except AdapterError as exc:
        session.fail(exc, job_id=job_id, detail={"reason": exc.reason})
        return _payload(
            session=session,
            job=job_payload,
            cv=cv,
            result=SubmissionResult(
                submitted=False,
                attempts=0,
                reason=exc.reason,
                retryable=True,
            ),
            message=str(exc),
        )
    except Exception as exc:  # noqa: BLE001 - a failure must still produce JSON and a session
        session.fail(exc, job_id=job_id, detail={"reason": "internal_error"})
        return _payload(
            session=session,
            job=job_payload,
            cv=cv,
            result=SubmissionResult(
                submitted=False,
                attempts=0,
                reason="internal_error",
            ),
            message=f"{type(exc).__name__}: {exc}",
        )
    finally:
        session.close(session_status)


def _payload(
    *,
    session: SessionRecorder,
    job: Mapping[str, object],
    cv: Path,
    result: SubmissionResult,
    message: str,
    questions: Sequence[str] = (),
) -> dict[str, object]:
    screenshots = sorted(
        path.relative_to(session.root).as_posix()
        for path in session.screenshots_dir.glob("*.png")
        if path.is_file()
    )
    return _envelope(
        run_id=session.run_id,
        job=job,
        cv=cv,
        result=result,
        message=message,
        questions=questions,
        artifacts={
            "session_dir": str(session.root),
            "session_json": str(session.root / "session.json"),
            "events": str(session.events_path),
            "screenshots": [str(session.root / name) for name in screenshots],
        },
    )


def _error_payload(
    *,
    job_id: str | None,
    reason: str,
    message: str,
    cv: Path | None = None,
    retryable: bool = False,
) -> dict[str, object]:
    return _envelope(
        run_id=None,
        job={"id": job_id},
        cv=cv,
        result=SubmissionResult(submitted=False, attempts=0, reason=reason, retryable=retryable),
        message=message,
        artifacts=_empty_artifacts(),
    )


def _empty_artifacts() -> dict[str, object]:
    return {
        "session_dir": None,
        "session_json": None,
        "events": None,
        "screenshots": [],
    }


def _envelope(
    *,
    run_id: str | None,
    job: Mapping[str, object],
    cv: Path | None,
    result: SubmissionResult,
    message: str,
    artifacts: Mapping[str, object],
    questions: Sequence[str] = (),
) -> dict[str, object]:
    failure: dict[str, object] | None = None
    if not result.verified:
        failure = {
            "reason": result.reason,
            "message": message,
            "retryable": result.retryable,
        }
        if questions:
            failure["questions"] = list(questions)
    return {
        "command": COMMAND,
        "status": "verified" if result.verified else "failed",
        "run_id": run_id,
        "job": dict(job),
        "result": _result_dict(result),
        "failure": failure,
        "artifacts": dict(artifacts),
        "cv": str(cv) if cv is not None else None,
    }


def _result_dict(result: SubmissionResult) -> dict[str, object]:
    return {
        "submitted": result.submitted,
        "verified": result.verified,
        "reason": result.reason,
        "attempts": result.attempts,
        "expected_cv": result.expected_cv,
        "selected_cvs": list(result.selected_cvs),
        "retryable": result.retryable,
    }


def _capture(session: SessionRecorder, stage: str, job_id: str) -> None:
    try:
        session.capture(stage, job_id=job_id)
    except Exception:  # noqa: BLE001 - evidence must never change the outcome
        pass


def _build_adapter(
    adapter_name: str,
    scenario: FakeScenario,
    paths: WorkspacePaths,
    environment: Mapping[str, str],
    *,
    job_id: str,
    cv: Path,
    answers: Path | None,
    apply_timeout: float,
) -> ApplicationAdapter:
    if adapter_name == "fake":
        return FakeApplicationAdapter(job_id=job_id, cv=cv, scenario=scenario)
    if answers is None:
        raise AssertionError("the real adapter requires an answers file")
    return RealApplicationAdapter(
        paths,
        job_id=job_id,
        cv=cv,
        answers=answers,
        environ=environment,
        apply_timeout=apply_timeout,
    )


def _build_watchdog(
    adapter_name: str,
    renderer_timeout: float,
    apply_timeout: float,
) -> RendererWatchdog:
    if adapter_name == "fake":
        return RendererWatchdog(renderer_timeout)
    # The guard wraps whole adapter methods, and one real method may run several
    # subprocesses with their own deadlines.  Keep the outer deadline above the
    # worst case (two preload calls, easyapply and the CV selection, or three
    # verification calls) so the adapter's precise ``RendererTimeout`` wins.
    outer = apply_timeout + 3 * DEFAULT_JOBINFO_TIMEOUT_SECONDS + renderer_timeout
    return RendererWatchdog(outer)


def _build_tailor(
    adapter_name: str,
    paths: WorkspacePaths,
    environment: Mapping[str, str],
) -> CvTailor:
    if adapter_name == "fake":
        return FakeCvTailor(paths)
    return CommandCvTailor(paths, environ=environment)


def _resolve_cv(
    raw: str | None,
    environment: Mapping[str, str],
    paths: WorkspacePaths,
    *,
    allow_cache: bool = False,
) -> tuple[Path | None, str | None]:
    configured = raw or environment.get("CAREER_OPS_CV")
    if configured:
        candidate = expand_path(configured, environment)
        if not candidate.is_file():
            return None, f"CV not found: {candidate}"
        return candidate.resolve(), None

    if allow_cache:
        return None, None

    candidates = sorted(
        paths.output.glob("cv-*.pdf"),
        key=lambda path: path.stat().st_mtime,
        reverse=True,
    )
    if not candidates:
        return None, (
            "no CV found: pass --cv, set CAREER_OPS_CV or generate one in "
            f"{paths.output}"
        )
    return candidates[0].resolve(), None


def _resolve_answers(
    raw: str | None,
    environment: Mapping[str, str],
    paths: WorkspacePaths,
) -> tuple[Path | None, str | None]:
    configured = raw or environment.get("CAREER_OPS_ANSWERS")
    if configured:
        candidate = expand_path(configured, environment)
        if not candidate.is_file():
            return None, f"answers file not found: {candidate}"
        return candidate.resolve(), None
    found = paths.read_config("answers-hermes.json")
    if found is None:
        return None, (
            f"answers file not found in {paths.config} or {paths.upstream / 'config'}"
        )
    return found.resolve(), None


def _positive_float(raw: str | None, default: float, name: str) -> float:
    if raw is None or not raw.strip():
        return default
    try:
        value = float(raw)
    except ValueError as exc:
        raise ValueError(f"{name} must be a number, got {raw!r}") from exc
    if value <= 0:
        raise ValueError(f"{name} must be greater than zero, got {raw!r}")
    return value


def _run_max_seconds(raw: float | None, environment: Mapping[str, str]) -> float | None:
    if raw is not None:
        value = raw
    else:
        value = _non_negative_float(
            environment.get("CAREER_OPS_RUN_MAX_SECONDS"),
            float(DEFAULT_RUN_MAX_SECONDS),
            "CAREER_OPS_RUN_MAX_SECONDS",
        )
    return None if value == 0 else value


def _run_max_attempts(raw: int | None, environment: Mapping[str, str]) -> int:
    if raw is not None:
        return raw
    return _positive_int(
        environment.get("CAREER_OPS_MAX_ATTEMPTS_PER_JOB"),
        DEFAULT_MAX_ATTEMPTS_PER_JOB,
        "CAREER_OPS_MAX_ATTEMPTS_PER_JOB",
    )


