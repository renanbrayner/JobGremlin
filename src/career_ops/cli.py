"""``career-ops-run`` — apply to LinkedIn jobs and report JSON.

The command is deliberately narrow: one explicit job or the first eligible job
from a candidate queue, one observable session.  In queue mode the CV is reused
from the cache or generated by the per-job tailor; ``--cv`` is a manual
override.  Success is reported only when LinkedIn confirms the application.
``--adapter fake`` runs the whole orchestration without a browser or a model and
is what the acceptance tests use.
"""

